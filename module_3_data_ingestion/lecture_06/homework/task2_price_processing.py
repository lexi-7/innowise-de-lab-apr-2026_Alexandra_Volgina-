# task2_price_processing.py
# Задание 2: Обработка прайс-листа конкурентов

# 1. Инициализировать список prices
prices = [100, -50, 300, 40, 800]

# 2. Очистить данные
# Удаляем отрицательное значение -50
prices.remove(-50)

# 3. Изменить список
# Добавляем новую цену 150 в конец списка
prices.append(150)

# 4. Отсортировать список
# Сортируем по возрастанию
prices.sort()

# 5. Создать новый список через List Comprehension
# Применяем НДС 20% (* 1.2) и оставляем только значения больше 100.0
tax_prices = [price * 1.2 for price in prices if price * 1.2 > 100.0]

# 6. Вывести в консоль
print(f"Базовый прайс (очищенный): {prices}")
print(f"Цены с НДС (>100): {tax_prices}")
print(f"Общая выручка: {sum(tax_prices)}")
print(f"Минимум: {min(tax_prices)}")
print(f"Максимум: {max(tax_prices)}")
