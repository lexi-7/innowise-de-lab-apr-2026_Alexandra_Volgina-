"""
Модуль для расчета геометрических параметров складских зон.

Назначение: Вычисление длины стороны квадратной зоны хранения
на основе известной площади.

Автор: Александра Волгина
Версия: 1.0
Дата: 2026
"""

import math

# Заранее заданная площадь зоны (кв. метры)
area_total = 225

# Запрос идентификатора зоны у пользователя
zone_id = input("Введите идентификатор зоны: ")

# Расчет длины стороны квадратной зоны
# Для квадрата: сторона = квадратный корень из площади
side_length = math.sqrt(area_total)

# Вывод итогового отчета
print(f"\nРасчет для объекта: {zone_id}")
print(f"Длина стены зоны: {side_length} метров")
